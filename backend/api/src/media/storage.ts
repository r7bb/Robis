import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve, sep } from 'node:path';

/**
 * Where uploaded files live, behind a port.
 *
 * Local disk in development, so the app runs on a laptop with nothing else
 * installed. An object store can replace it later by implementing these
 * three calls; nothing above this file knows where the bytes go.
 */
export type MediaStorage = {
  put: (key: string, bytes: Uint8Array) => Promise<void>;
  get: (key: string) => Promise<Uint8Array | null>;
  delete: (key: string) => Promise<void>;
};

/**
 * Keys are generated by the server (`avatars/<uuid>.webp`), never taken from
 * a request. This check is the second line anyway: a key that would resolve
 * outside the root is refused, so no path traversal can reach the disk.
 */
const KEY = /^[a-z0-9-]+\/[a-z0-9-]+\.[a-z0-9]+$/;

export function localDiskStorage(root: string): MediaStorage {
  const base = resolve(root);

  function pathFor(key: string): string {
    const path = resolve(join(base, key));
    if (!KEY.test(key) || !path.startsWith(base + sep)) {
      throw new Error(`invalid media key: ${key}`);
    }
    return path;
  }

  return {
    async put(key, bytes) {
      const path = pathFor(key);
      // Owner read/write only: these are pictures of people, and nothing else
      // on the machine has a reason to read them.
      await mkdir(dirname(path), { recursive: true, mode: 0o700 });
      await writeFile(path, bytes, { mode: 0o600 });
    },
    async get(key) {
      try {
        return new Uint8Array(await readFile(pathFor(key)));
      } catch (error) {
        if ((error as NodeJS.ErrnoException).code === 'ENOENT') return null;
        throw error;
      }
    },
    async delete(key) {
      await rm(pathFor(key), { force: true });
    },
  };
}
