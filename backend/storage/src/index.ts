import { mkdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve, sep } from 'node:path';

/**
 * Where uploaded files live, behind a port.
 *
 * Two drivers: local disk, so the app runs on a laptop with nothing else
 * installed, and any S3-compatible object store for anything deployed.
 * Nothing above this file knows which one it is talking to.
 *
 * There are no public URLs. Every read goes through an API route that checks
 * who is asking first and then streams the object, so a stored file is never
 * reachable by anyone who merely has its key.
 */
export type StoredObject = { stream: ReadableStream<Uint8Array>; size: number };

export type MediaStorage = {
  put: (key: string, bytes: Uint8Array, contentType: string) => Promise<void>;
  /** A stream of the object, or null if there is none. */
  open: (key: string) => Promise<StoredObject | null>;
  exists: (key: string) => Promise<boolean>;
  /** Idempotent: deleting a missing object is not an error. */
  delete: (key: string) => Promise<void>;
};

/**
 * Keys are generated by the server (`avatars/<uuid>.webp`,
 * `attachments/<workspace>/<uuid>.png`), never taken from a request. This is
 * the second line anyway: a key outside this shape is refused by every
 * driver, so no path traversal can reach the disk or the bucket.
 */
const KEY = /^(?:[a-z0-9-]+\/){1,3}[a-z0-9-]+\.[a-z0-9]+$/;

function assertKey(key: string) {
  if (!KEY.test(key)) throw new Error(`invalid media key: ${key}`);
}

export function localDiskStorage(root: string): MediaStorage {
  const base = resolve(root);

  function pathFor(key: string): string {
    assertKey(key);
    const path = resolve(join(base, key));
    if (!path.startsWith(base + sep)) throw new Error(`invalid media key: ${key}`);
    return path;
  }

  return {
    async put(key, bytes) {
      const path = pathFor(key);
      // Owner read/write only: these are pictures of people, and nothing else
      // on the machine has a reason to read them.
      await mkdir(dirname(path), { recursive: true, mode: 0o700 });
      await writeFile(path, bytes, { mode: 0o600 });
    },
    async open(key) {
      const file = Bun.file(pathFor(key));
      if (!(await file.exists())) return null;
      return { stream: file.stream(), size: file.size };
    },
    async exists(key) {
      return Bun.file(pathFor(key)).exists();
    },
    async delete(key) {
      await rm(pathFor(key), { force: true });
    },
  };
}

/** Bun's S3 client reports a missing object with a code or a 404 status. */
function isNotFound(error: unknown): boolean {
  const { code, status } = (error ?? {}) as { code?: string; status?: number };
  return code === 'NoSuchKey' || code === 'ERR_S3_FILE_NOT_FOUND' || status === 404;
}

export type S3Options = {
  endpoint: string;
  bucket: string;
  accessKeyId: string;
  secretAccessKey: string;
  region: string;
};

/**
 * Any S3-compatible store, through Bun's built-in client: no SDK dependency.
 *
 * Path-style addressing (the bucket in the path, not the hostname), which
 * every S3-compatible server accepts and which needs no DNS per bucket.
 * Objects are written private; nothing here can produce a public URL.
 */
export function s3Storage(options: S3Options): MediaStorage {
  const client = new Bun.S3Client({
    endpoint: options.endpoint,
    bucket: options.bucket,
    accessKeyId: options.accessKeyId,
    secretAccessKey: options.secretAccessKey,
    region: options.region,
    virtualHostedStyle: false,
  });

  return {
    async put(key, bytes, contentType) {
      assertKey(key);
      await client.write(key, bytes, { type: contentType });
    },
    async open(key) {
      assertKey(key);
      const file = client.file(key);
      // One HEAD rather than exists-then-stat: a missing object is the only
      // error that means "none", and anything else (a 403, an outage) is
      // left to surface as a failure rather than pass as not-found.
      let size: number;
      try {
        ({ size } = await file.stat());
      } catch (error) {
        if (isNotFound(error)) return null;
        throw error;
      }
      return { stream: file.stream(), size };
    },
    async exists(key) {
      assertKey(key);
      return client.exists(key);
    },
    async delete(key) {
      assertKey(key);
      await client.delete(key);
    },
  };
}

export type StorageEnv = {
  STORAGE_DRIVER: 'local' | 's3';
  MEDIA_DIR: string;
  S3_ENDPOINT: string;
  S3_BUCKET: string;
  S3_ACCESS_KEY_ID: string;
  S3_SECRET_ACCESS_KEY: string;
  S3_REGION: string;
};

/** The driver the environment asks for. */
export function storageFromEnv(env: StorageEnv): MediaStorage {
  if (env.STORAGE_DRIVER === 'local') return localDiskStorage(env.MEDIA_DIR);

  return s3Storage({
    endpoint: env.S3_ENDPOINT,
    bucket: env.S3_BUCKET,
    accessKeyId: env.S3_ACCESS_KEY_ID,
    secretAccessKey: env.S3_SECRET_ACCESS_KEY,
    region: env.S3_REGION,
  });
}
